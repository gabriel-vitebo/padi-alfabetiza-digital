test('invalid session and invalid API requests are handled without technical leaks',async({page,request})=>{
  await page.goto('/resultado/00000000-0000-4000-8000-000000000000')
  await expect(page.getByText('Acesso à sessão não autorizado. Use o dispositivo em que iniciou a participação.')).toBeVisible()
  const bad=await request.post('/api/surveys/research/start',{data:{profile:{},total:1}})
  expect(bad.status()).toBe(400)
  const invalid=await request.get('/api/dashboard/summary?area=invalid')
  expect(invalid.status()).toBe(400)
  const response=await invalid.json()
  expect(JSON.stringify(response)).not.toContain('DATABASE_URL')
})

test('legacy completed marker allows participation; an inaccessible incomplete session can be replaced',async({page})=>{
  await page.goto('/')
  await page.evaluate(()=>localStorage.setItem('padi:research:v1',JSON.stringify({completed:true,sessionId:'00000000-0000-4000-8000-000000000001'})))
  await page.goto('/pesquisa')
  await expect(page.getByRole('button',{name:'Começar pesquisa'})).toBeVisible()
  await expect(page.getByRole('button',{name:'Iniciar nova participação'})).toHaveCount(0)
  await page.evaluate(()=>localStorage.setItem('padi:research:v1',JSON.stringify({completed:false,sessionId:'00000000-0000-4000-8000-000000000001'})))
  await page.reload()
  await page.getByRole('button',{name:'Iniciar nova participação'}).click()
  await expect(page.getByRole('button',{name:'Começar pesquisa'})).toBeVisible()
  expect(await page.evaluate(()=>localStorage.getItem('padi:research:v1'))).toBeNull()
})

test('general public can participate without providing an area',async({page})=>{
  await page.goto('/pesquisa')
  await expect(page.locator('select')).toHaveCount(1)
  await page.getByLabel('Área de estudo ou atuação').selectOption('prefiro-nao-informar')
  const request=page.waitForRequest(r=>r.url().endsWith('/api/surveys/research/start'))
  await page.getByRole('button',{name:'Começar pesquisa'}).click()
  expect((await request).postDataJSON()).toEqual({profile:{area:'prefiro-nao-informar'}})
  await expect(page.getByText('Pergunta 1 de 10')).toBeVisible()
})
