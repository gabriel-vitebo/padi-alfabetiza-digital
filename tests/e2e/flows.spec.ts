import { test, expect } from '@playwright/test'

test('mobile research: contextual data, original session resume, completion and result recovery', async ({ page }) => {
  await page.setViewportSize({width:390,height:844})
  await page.goto('/pesquisa?total=1')
  await expect(page.locator('select')).toHaveCount(1)
  await page.getByLabel('Área de estudo ou atuação').selectOption('tecnologia')
  const started=page.waitForResponse(r=>r.url().endsWith('/api/surveys/research/start'))
  await page.getByRole('button',{name:'Começar pesquisa'}).click()
  const data=await (await started).json()
  expect(data.questions).toHaveLength(10)
  expect(data.accessToken).toMatch(/^[A-Za-z0-9_-]{43}$/)
  expect((await page.request.get(`/api/sessions/${data.sessionId}`)).status()).toBe(403)
  expect((await page.request.get(`/api/sessions/${data.sessionId}`, {headers:{Authorization:`Bearer ${'x'.repeat(43)}`}})).status()).toBe(403)
  expect(JSON.stringify(data)).not.toContain('score')
  expect(JSON.stringify(data)).not.toContain('justification')
  const first=await page.locator('[data-question-heading]').textContent()
  await page.getByRole('radio').first().check({force:true})
  await expect.poll(async()=>{
    const response=await page.request.get(`/api/sessions/${data.sessionId}`,{headers:{Authorization:`Bearer ${data.accessToken}`}})
    return (await response.json()).answers.length
  }).toBe(1)
  await page.getByRole('button',{name:'Continuar',exact:true}).click()
  await page.reload()
  await expect(page.getByText('Pergunta 2 de 10')).toBeVisible()
  await page.getByRole('button',{name:'Voltar',exact:true}).click()
  await expect(page.locator('[data-question-heading]')).toHaveText(first!)
  await expect(page.getByRole('radio').first()).toBeChecked()
  await expect(page.locator('[data-question-heading]')).toBeFocused()
  for(let i=0;i<10;i++) {
    await page.getByRole('radio').first().check({force:true})
    await page.getByRole('button',{name:i===9?'Concluir e ver resultado':'Continuar',exact:true}).click()
  }
  await expect(page).toHaveURL(new RegExp(`/resultado/${data.sessionId}`))
  await expect(page.getByRole('heading',{name:'Desempenho por competência'})).toBeVisible()
  await page.reload()
  await expect(page.getByText('20 de 20 pontos possíveis')).toBeVisible()
  const outsider = await page.context().browser()!.newContext()
  const outsiderPage = await outsider.newPage()
  await outsiderPage.goto(page.url())
  await expect(outsiderPage.getByText('Acesso à sessão não autorizado. Use o dispositivo em que iniciou a participação.')).toBeVisible()
  expect((await outsider.request.get(`http://127.0.0.1:3107/api/sessions/${data.sessionId}/result`)).status()).toBe(403)
  await outsider.close()
  await expect(page.getByRole('button',{name:/refazer|novo desafio/i})).toHaveCount(0)
  await page.getByRole('link',{name:'Voltar ao início'}).click()
  await page.goto('/pesquisa')
  await expect(page.getByRole('button',{name:'Começar pesquisa'})).toBeVisible()
  await expect(page.locator('select')).toHaveCount(1)
  await page.getByLabel('Área de estudo ou atuação').selectOption('tecnologia')
  const restarted=page.waitForResponse(r=>r.url().endsWith('/api/surveys/research/start'))
  await page.getByRole('button',{name:'Começar pesquisa'}).click()
  expect((await (await restarted).json()).sessionId).not.toBe(data.sessionId)
  await expect(page.getByText('Pergunta 1 de 10')).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
})

test('fair has five questions and no global diagnostic; result survives reload',async({page})=>{
  await page.goto('/desafio')
  await page.getByRole('button',{name:'Começar desafio'}).click()
  await expect(page.getByText('Pergunta 1 de 5')).toBeVisible()
  for(let i=0;i<5;i++) {
    await page.getByRole('radio').nth(1).check({force:true})
    await page.getByRole('button',{name:i===4?'Concluir e ver resultado':'Continuar',exact:true}).click()
  }
  await expect(page).toHaveURL(/\/resultado\/[a-f0-9-]+/)
  await expect(page.getByText(/Experiência rápida: este resultado/)).toBeVisible()
  await expect(page.getByText('Percentual geral nas situações apresentadas')).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('heading',{name:'Suas respostas no desafio'})).toBeVisible()
  await expect(page.getByRole('link',{name:'Voltar ao desafio'})).toHaveCount(0)
  await page.goto('/desafio')
  await expect(page.getByRole('button',{name:'Começar desafio'})).toBeVisible()
})

